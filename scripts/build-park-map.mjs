// Generates src/data/park-map.ts: the US outline as SVG paths and every park's
// position in the same 975x610 Albers USA space, plus collision-separated pin
// positions so dense regions (Utah, Sequoia/Kings Canyon, South Florida) stay
// legible. Rerun after adding a visited park:
//
//   npm run build:park-map
//
// us-atlas's *-albers-10m files are already projected with
// geoAlbersUsa().scale(1300).translate([487.5, 305]), so parks use that exact
// projection to line up with the outline.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { geoAlbersUsa, geoPath } from 'd3-geo';
import { feature, mesh } from 'topojson-client';
import { forceSimulation, forceX, forceY, forceCollide } from 'd3-force';
import { parks, isVisited } from '../src/data/parks.ts';

const WIDTH = 975;
const HEIGHT = 610;

// Pin radii in map units for each layout. A layout's radius is chosen so the
// pin is the intended on-screen size at that layout's typical rendered map width:
//   wide:    map ~900px wide  -> 44px pins
//   compact: map ~360px wide  -> 22px pins (tap targets are padded to 44px in CSS)
const LAYOUTS = {
  wide: { visited: 24, empty: 9, padding: 2 },
  compact: { visited: 30, empty: 11, padding: 2 },
};

// geoAlbersUsa has no inset for the territories, so they get hand-placed spots
// in the empty lower corners of the map.
const MANUAL_POSITIONS = {
  'american-samoa': [370, 588],
  'virgin-islands': [935, 585],
};

const root = fileURLToPath(new URL('..', import.meta.url));
const atlas = JSON.parse(
  readFileSync(`${root}node_modules/us-atlas/states-albers-10m.json`, 'utf8'),
);

const round = (n) => Math.round(n * 10) / 10;
const path = geoPath().digits(0);
const nation = path(feature(atlas, atlas.objects.nation));
const stateBorders = path(mesh(atlas, atlas.objects.states, (a, b) => a !== b));

const states = feature(atlas, atlas.objects.states).features;
const insetBox = (fips) => {
  const [[x0, y0], [x1, y1]] = path.bounds(states.find((s) => s.id === fips));
  // Clamped to the viewBox: the Aleutians cross the antimeridian and project off the left edge.
  const pad = 8;
  const left = Math.max(0, x0 - pad);
  const top = Math.max(0, y0 - pad);
  const right = Math.min(WIDTH, x1 + pad);
  const bottom = Math.min(HEIGHT, y1 + pad);
  return { x: round(left), y: round(top), width: round(right - left), height: round(bottom - top) };
};
const insets = { alaska: insetBox('02'), hawaii: insetBox('15') };

const projection = geoAlbersUsa().scale(1300).translate([WIDTH / 2, HEIGHT / 2]);

const points = parks.map((p) => {
  const projected = MANUAL_POSITIONS[p.id] ?? projection(p.coordinates);
  if (!projected) throw new Error(`No map position for ${p.id}; add it to MANUAL_POSITIONS`);
  return { id: p.id, visited: isVisited(p), x: projected[0], y: projected[1] };
});

function separate({ visited, empty, padding }) {
  const nodes = points.map((p) => ({ ...p, tx: p.x, ty: p.y, r: p.visited ? visited : empty }));
  const sim = forceSimulation(nodes)
    .force('x', forceX((d) => d.tx).strength(0.25))
    .force('y', forceY((d) => d.ty).strength(0.25))
    .force('collide', forceCollide((d) => d.r + padding).iterations(4))
    .stop();
  for (let i = 0; i < 400; i++) sim.tick();
  return Object.fromEntries(
    nodes.map((n) => [
      n.id,
      [round(Math.min(WIDTH - n.r, Math.max(n.r, n.x))), round(Math.min(HEIGHT - n.r, Math.max(n.r, n.y)))],
    ]),
  );
}

const truePositions = Object.fromEntries(points.map((p) => [p.id, [round(p.x), round(p.y)]]));
const pinPositions = Object.fromEntries(
  Object.entries(LAYOUTS).map(([name, cfg]) => [name, separate(cfg)]),
);

const out = `// Generated by scripts/build-park-map.mjs. Do not edit by hand.

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

export const nationPath = ${JSON.stringify(nation)};
export const stateBordersPath = ${JSON.stringify(stateBorders)};

export const insets = ${JSON.stringify(insets)};

// Pin radius (map units) each layout was separated for.
export const pinRadii = ${JSON.stringify(LAYOUTS)};

// Projected [x, y] of each park's real location.
export const truePositions: Record<string, [number, number]> = ${JSON.stringify(truePositions)};

// Collision-separated [x, y] pin centers, per layout.
export const pinPositions: Record<'wide' | 'compact', Record<string, [number, number]>> = ${JSON.stringify(pinPositions)};
`;

writeFileSync(`${root}src/data/park-map.ts`, out);

for (const [name, positions] of Object.entries(pinPositions)) {
  const moved = points
    .filter((p) => p.visited)
    .map((p) => [p.id, Math.hypot(positions[p.id][0] - p.x, positions[p.id][1] - p.y)])
    .sort((a, b) => b[1] - a[1]);
  console.log(`${name}: visited pins moved furthest ->`, moved.slice(0, 5).map(([id, d]) => `${id} ${d.toFixed(0)}`).join(', '));
}
console.log(`wrote src/data/park-map.ts (${(out.length / 1024).toFixed(0)} KB)`);
